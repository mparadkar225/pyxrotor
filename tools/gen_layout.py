"""Generate src/pyxrotor/_layout.py from XROTOR.INC.

    python tools/gen_layout.py

The layout lists every COMMON block variable with its type and Fortran bounds. pyxrotor's
State is built from it, so the port carries exactly XROTOR's state; a test checks that the
committed file still matches XROTOR.INC.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from reference.commons import parse_include, parameters  # noqa: E402

INCLUDE = ROOT / "reference" / "xrotor-7.55" / "src" / "XROTOR.INC"
OUT = ROOT / "src" / "pyxrotor" / "_layout.py"


def render() -> str:
    blocks = parse_include(INCLUDE)
    lines = [
        '"""XROTOR 7.55 COMMON-block layout. GENERATED by tools/gen_layout.py from XROTOR.INC;',
        'do not edit by hand."""',
        "",
        "# block -> [(name, kind, fortran_bounds)], kind in real|integer|logical|character:N",
        "BLOCKS = {",
    ]
    for blk in blocks.values():
        lines.append(f"    {blk.name!r}: [")
        for v in blk.vars:
            kind = f"character:{v.itemsize}" if v.kind == "character" else v.kind
            lines.append(f"        ({v.name!r}, {kind!r}, {tuple(v.bounds)!r}),")
        lines.append("    ],")
    lines.append("}")
    lines.append("")
    params = parameters(INCLUDE)
    lines.append("PARAMETERS = {" + ", ".join(f"{k!r}: {v!r}" for k, v in params.items()) + "}")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT}")
