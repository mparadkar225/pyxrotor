C     NASA CR-176883 (Korkan, Camba & Morris, Texas A&M, 1986), chapter III:
C     NACA 16-series airfoil data bank, subroutine CLCD (report pp. 143-146),
C     renamed CLCD16 (the Clark Y bank also has a CLCD).
C     Transcribed from the 300 dpi page images. Omitted: the limitation
C     warnings (WRITE/FORMAT), which don't change any result.
C
      SUBROUTINE CLCD16(XM,ALPHA,CL,CD,ICL,ICD,CHORD,XTC,XRN,XCLI,XR
     &,WA,VIS,DEN,CDFRIC,CDLIFT,CDCAMB,CDZERO)
C
C
      DIMENSION CDD(6),CLIT(6),A(6),B(6),C(6),D(6),E(6),F(6),G(6)
      DIMENSION TB(11),DMACH(11),CDO(11),CDO1(6),TB1(6),AA(6),BB(6)
      DIMENSION CC(6),DD(6),EE(6),FF(6)
      DOUBLE PRECISION AA,BB,CC,DD,EE,FF
      DATA A/1.325276,.1024011,.2890272,.5288957,1.177606,2.125449/
      DATA B/-5.133061,-.0976595,-.2461832,-.0205697,-.2953677,.1974199/
      DATA C/8.412967,-.2752136,-.8075892,-2.787452,-5.423342,-11.9608/
      DATA D/-7.325109,.5574539,1.520081,4.335364,8.694619,18.21422/
      DATA E/3.522405,-.3924382,-1.018046,-2.761126,-5.583289,-11.50479/
      DATA F/-.8777567,.1226128,.3042805,.8093843,1.64263,3.357388/
      DATA G/.087806,-.0140459,-.0334875,-.0889465,-.1814412,-.3697504/
      DATA TB/.031,.0625,.1,.1375,.175,.2125,.25,.2875,.325,.3625,.4/
      DATA CDO/0.0,.00025,.00065,.0013,.0022,.0033,.00465,.0061,
     &.0078,.01,.013/
      DATA DMACH/.9,.84,.79,.75,.72,.7,.68,.665,.65,.6375,.62/
      DATA AA/-5.834527753,-1.45916514,8.3327673,2.6038473,-.10428842,.2
     &08297374/
      DATA BB/37.09086074,9.58857686,-51.4547602,-16.2479854,.78201755,-
     &1.2497732/
      DATA CC/-94.01887327,-25.1902339,126.241026,40.198068,-2.2988001,2
     &.94734747/
      DATA DD/118.8401952,33.12056567,-153.736709,-49.206188,3.3320883,-
     &3.39928973/
      DATA EE/-74.98024889,-21.858250,92.8384573,29.7250413,-2.3960093,
     &1.903809351/
      DATA FF/18.94459392,5.83350647,-22.1932814,-7.0552833,.689991999,-
     &.408891283/
      PLAM=(33.+1./3.)*XR**2+(8.+1./3.)*XR+17.0
      IF(XM.LT.1.0) GO TO 1
      DCLDA=.0698/SQRT(XM**2-1)
      GO TO 2
    1 IF(ICL.EQ.0) DCLDA=.1096*(1-XTC)/SQRT(1-XTC**2)
      IF(ICL.EQ.0) GO TO 2
      DCLDA=.1096/SQRT(1-(XM)**2)
      IF((XM+XTC).GE.1.0) GO TO 2
      DCLDA=.1096*(1.-XTC)/SQRT(1-(XM+XTC)**2)
    2 CL=ALPHA*DCLDA
      XRN=DEN*XM*WA*CHORD/VIS
C     XRN=3000000.0     IS THIS SUPPOSE TO BE HERE? --- WINTER
C     IF(ICD.EQ.0) RETURN
      DELTA=CL-XCLI
      XMXT=XM/(.9-XTC)
      DELCD=(XMXT**2-XMXT-.1765)*(-.4397*DELTA**2+.1173*DELTA-.0938)
      TESTM=(DELCD-.03)*(.9-.875)/(.03-.08)+.9
      IF(XMXT.GT.TESTM) GO TO 3
      GO TO 4
    3 SLOPE=-117.218415*DELTA**6+321.890357*DELTA**5-332.087766*DELTA**4
     &+151.8614153*DELTA**3-24.597998*DELTA**2-2.6451615*DELTA+1.48
      DELCD=SLOPE*(XMXT-1.011111)+.0911111
    4 IF(XM.GE.1.0) DELCD=SQRT(XM**2-1)/4.
      IF(XM.GE.1.0) DELTA=CL
      CLDMX=0.8
      CDLIFT=DELCD*DELTA**2
      IF(CDLIFT.LT.0.0) CDLIFT=0.0
      CDFRIC=2.65/SQRT(XRN)+(100-PLAM)/100.*(.944/(ALOG10(XRN)**2.6)-2.6
     &5/SQRT(XRN))
      IF(XMXT.GT.1.0) GO TO 8
      DO 5 I=1,6
      CDD(I)=A(I)*XMXT**6+B(I)*XMXT**5+C(I)*XMXT**4+D(I)*XMXT**3+E(I)*XM
     &XT**2+F(I)*XMXT+G(I)
    5 CLIT(I)=FLOAT(I)/10.+.1
      SUM=0.0
      DO 7 IX=1,6
      S=CDD(IX)
      DO 6 JX=1,6
      IF(JX.EQ.IX) GO TO 6
      S=S*(XCLI-CLIT(JX))/(CLIT(IX)-CLIT(JX))
    6 CONTINUE
      SUM=SUM+S
    7 CONTINUE
      CLDMIN=0.0
      CLDMAX=0.7
      CDCAMB=SUM
      IF(CDCAMB.GT.0.0) GO TO 9
    8 CDCAMB=0.0
    9 IF(XM.GE..95) GO TO 14
      IF(XTC.LE..03) GO TO 19
      SUM=0.0
      DO 11 IX=1,11
      S=CDO(IX)
      DO 10 JX=1,11
      IF(JX.EQ.IX) GO TO 10
      S=S*(XTC-TB(JX))/(TB(IX)-TB(JX))
   10 CONTINUE
      SUM=SUM+S
   11 CONTINUE
      CDZERO=SUM
      SUM=0.0
      DO 13 IX=1,11
      S=DMACH(IX)
      DO 12 JX=1,11
      IF(JX.EQ.IX) GO TO 12
      S=S*(XTC-TB(JX))/(TB(IX)-TB(JX))
   12 CONTINUE
      SUM=SUM+S
   13 CONTINUE
      DIVMAC=SUM
      IF(XM.LE.DIVMAC) GO TO 18
      XCHANG=.7225+(XM-DIVMAC)
      YCHANG=CDZERO-.0023845
      CDZERO=-37732.79544*XCHANG**5+143059.1078*XCHANG**4-216835.3262*XC
     &HANG**3+164241.3211*XCHANG**2-62170.09813*XCHANG+9408.610638+YCHAN
     &G
      GO TO 18
   14 DO 15 I=1,6
      CDO1(I)=AA(I)*XM**5+BB(I)*XM**4+CC(I)*XM**3+DD(I)*XM**2+EE(I)*XM+F
     &F(I)
   15 TB1(I)=FLOAT(I)/100.
      SUM=0.0
      DO 17 IX=1,6
      S=CDO1(IX)
      DO 16 JX=1,6
      IF(JX.EQ.IX) GO TO 16
      S=S*(XTC-TB1(JX))/(TB1(IX)-TB1(JX))
   16 CONTINUE
      SUM=SUM+S
   17 CONTINUE
      CDZERO=SUM
   18 IF(CDZERO.LT.0.0) CDZERO=0.0
      GO TO 20
   19 CDZERO=0.0
   20 CD=CDLIFT+CDFRIC+CDCAMB+CDZERO
      IF(ICL.EQ.0) CD=CDFRIC
      XRN=XRN/1000000.
C
      RETURN
      END
