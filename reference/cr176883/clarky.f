C     NASA CR-176883 (Korkan, Camba & Morris, Texas A&M, 1986), chapter I:
C     Clark Y airfoil data bank (Haines & Monaghan, R&M 2036, 1945), the
C     lift and drag routines (report pp. 40-62, PDF pp. 48-69).
C     Transcribed from the 300 dpi page images. Omitted: the limitation
C     warnings (WRITE/FORMAT), which don't change any result, and the
C     moment and coordinate routines CMFF and CYCOOR. ATMCON is the one
C     in atmcon.f. The main program (PDF pp. 46-47) does, per Mach number
C     HM and angle ALPHA (deg, to the chord line):
C        CALL ATMCON(ALTUDE,TEMP,PRES,DEN,VIS,WA)
C        CALL CLTMAX(T,NCLD,ALPHLO,DNCLD)
C        RN(K)=DEN*HM(K)*WA*CHORD/VIS
C        ALPHAO(J)=ALPHA(J)-ALPHLO
C        CALL CLCD(ALPHAO(J),T,HM(K),CL(K,J),CD(K,J),NCL,NCD)
C     The Reynolds number is printed but not used: the data are for
C     the Reynolds numbers of the R&M 2036 tests.
C
C     Renamed for the shared library: the listing's CLCD is CLCDCY. The
C     listing's own ATMCON (p. 60-61 of the report) computes the same
C     thing as atmcon.f and is dropped. Listing oddities kept as printed:
C     * HMLF: 'IF(ALPHAO.LT.3.) GO TO 12' is commented out and IMPROV=1,
C       so the drag-critical table E (labels 12-20) is dead code and
C       ALPHAO < 3 uses the 3 deg column. HMLF writes ALPHAO (restored).
C     * CDSF looks up its interval with HM but interpolates at H = M-MD.
C     * AOF's A: 0.0991 at t/c 0.10, then 0.0999 at 0.11.
C     * CD23F CD5(4) = .2 and CD30F HM8 = ...,.68,.665,... as printed.
C     * IF(H.LE.0.4) GO TO n in CLFF and CDFF jump to the next line.
C
      SUBROUTINE CLCDCY(ALPHAO,T,HM,CL,CD,NCL,NCD)
      IF(NCL.NE.0) CL=CLFF(ALPHAO,T,HM)
      IF(NCD.NE.0) CD=CDFF(T,ALPHAO,HM)
      RETURN
      END
C
      FUNCTION CLFF(ALPHAO,T,HM)
      IF(T.LT.0.16) GO TO 1
      CLFF=ALPHAO*THKSLP(T,ALPHAO,HM)
      RETURN
    1 AO=AOF(T,ALPHAO,HM)
      HML=HMLF(T,ALPHAO,HM)
      H=HM-HML
      CLO=AO*ALPHAO
      IF(HM.LE.HML) CLFF=CLO/SQRT(1.-HM*HM)
      IF(H.LE.0.4) GO TO 2
    2 IF(HM.GT.HML)CLFF=CLO/SQRT(1.-HML*HML)+CLSF(H)
      RETURN
      END
