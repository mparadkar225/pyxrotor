      RETURN
      END
C
      FUNCTION GETF(NMAX,N,XHM,YCD,T,ALPHAO,HM)
      DIMENSION XHM(1),YCD(1),U(3),V(3)
      IF(HM.GT.XHM(1)) GO TO 1
      GETF=YCD(1)
      RETURN
    1 CALL OUT(NMAX,N,JS,JL,XHM,HM)
      DO 2 J=JS,JL
      U(J-JS+1)=XHM(J)
      V(J-JS+1)=YCD(J)
    2 CONTINUE
      GETF=YLAGN(U,V,N,HM)
      RETURN
      END
C
      SUBROUTINE OUT(NMAX,N,IS,IL,Y,X)
      DIMENSION Y(1)
      IS=1
      IL=IS+N-1
      IF(X.LE.Y(IL)) RETURN
      IL=NMAX
      IS=IL-N+1
      IF(X.GE.Y(IS)) RETURN
      IS=1
    1 IL=IS+N-1
      IF((X-Y(IS))*(X-Y(IL)).LE. 0.) RETURN
      IS=IL
      GO TO 1
      END
C
      FUNCTION YLAGN(X,Y,N,Z)
      DIMENSION X(1),Y(1)
      SUM=0.
      DO 1 I=1,N
      S=1.
      DO 2 J=1,N
      IF(J.EQ.I) GO TO 2
      S=S*(Z-X(J))/(X(I)-X(J))
    2 CONTINUE
      SUM=SUM+S*Y(I)
    1 CONTINUE
      YLAGN=SUM
      RETURN
      END
C
C     CLTMAX: design CL from (T/C)MAX, or (T/C)MAX from design CL when
C     NCLD is not 0 (then T is overwritten), and the zero-lift angle
C     ALPHLO (deg). DNCLD = 0 or 1 says which was computed.
      SUBROUTINE CLTMAX(T,NCLD,ALPHLO,DNCLD)
      DIMENSION ALPHAO(21)
      REAL NCLD
      IF(NCLD.NE.0.) GO TO 100
      TCMIN=0.06
      TCMAX=0.22
      NCLD=(-0.16879+SQRT(0.02849+0.496405*T))/0.2482025
      AOI=AOIOF(T)
      ALPHLO=NCLD/(-AOI)
      DNCLD=0.
      GO TO 889
  100 CONTINUE
      CLDMIN=0.30
      CLDMAX=0.90
      IF(NCLD.GE.0.0) T=0.1241*NCLD**2+0.16879*NCLD
      IF(NCLD.LE.0.0) T=0.1241*NCLD**2+0.16879*NCLD
      AOI=AOIOF(T)
      ALPHLO=NCLD/(-AOI)
      DNCLD=1.
      GO TO 889
  889 RETURN
      END
C
      FUNCTION AOIOF(T)
      DIMENSION A(6),H(6),X(3),Y(3)
      DATA A/0.1032,0.1012,0.0991,0.0952,0.0914,0.0876/
      DATA H/0.06,0.08,0.10,0.14,0.18,0.22/
      N=2
      AOIOF=0.1096
      IF(T.LT.0.06) RETURN
      IS=1
      IL=IS+N-1
    1 IF(IL.GE.6) GO TO 2
      IF((T-H(IS))*(T-H(IL)).LE.0.) GO TO 3
      IS=IL
      IL=IS+N-1
      GO TO 1
    2 IS=6-N+1
      IL=6
    3 DO 4 I=IS,IL
      X(I-IS+1)=H(I)
      Y(I-IS+1)=A(I)
    4 CONTINUE
      AOIOF=YLAGN(X,Y,N,T)
      RETURN
      END
