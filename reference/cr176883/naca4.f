C
C     SUBROUTINE LINEAR INTERPOLATES LINEARLY BETWEEN POINTS
      SUBROUTINE LINEAR( NU, XIN, YIN, XOUT, YOUT )
      DIMENSION XIN(NU), YIN(NU)
      INTEGER  F
      NM1 = NU-1
      F = 1
C     TEST FOR OFF LOW END
      IF(XOUT .LT. XIN(1)) GO TO 110
      F = NM1
C     TEST FOR OFF HIGH END
      IF(XOUT .GT. XIN(NU)) GO TO 110
C     IN RANGE
      DO 120  II = 2,NM1
      F = II-1
      IF(XOUT .LE. XIN(II)) GO TO 110
  120 CONTINUE
      F = NM1
C     SLOPE INTERCEPT FORMULA
  110 CONTINUE
      IP1 = F+1
      SLP = (YIN(IP1)-YIN(F))/(XIN(IP1)-XIN(F))
      B2 = YIN(F)-XIN(F)*SLP
      YOUT = SLP*XOUT+B2
      RETURN
      END
