C     NASA CR-176883 (Korkan, Camba & Morris, Texas A&M, 1986), chapter II:
C     NACA 4-digit (maximum camber at mid-chord, NACA x5xx) data bank,
C     report pp. 102-111 (PDF pp. 109-118). Transcribed from the page images.
C     The main program's CL/CD arithmetic (pp. 103-104) is the subroutine
C     NACA4 below, one (CLD or Z, TC, ALPHA, MACH) point per call. Omitted:
C     the limitation warnings and output (WRITE/FORMAT), and the moment and
C     coordinate routines QCCM, FDCOOR, FDCR, AREA, which don't affect CL/CD.
C
C     Listing oddity: X8's continuation line reads "01,.2,.3,.4,.5" with the
C     "0" in column 6. Column 6 must be non-blank and non-zero for a
C     continuation, so the "0" is read as the letter O and X8(13) = 1., as the
C     listing compiles. The table's other steps say .1 was meant: pass LFIXX8
C     = .TRUE. for that.
C
      SUBROUTINE NACA4(CAMP,TC,CLD,Z,ALPHA,XMACH,RE,ALT,CHORD,LFIXX8,
     &CL,CD,CLMX,CLOPT,X,CDMIN,DELCD)
C     CAMP = 0: CLD given, Z computed; 1: Z given, CLD computed.
C     ALPHA (deg) is measured from the design attitude: CL = CLD + dCL.
C     RE .LE. 0: computed from MACH, ALT (ft) and CHORD (ft), as RE = 0.0
C     in the listing's DATA does. RE is returned.
      LOGICAL LFIXX8
      REAL MACH
      MACH=XMACH
      IF (RE .GT. 0.0) GO TO 88
      CALL ATMCN4(ALT,DEN,VIS,WA)
      OMACH = MACH
      IF (MACH .EQ. 0.0) MACH = 0.05
      VEL = MACH*WA
      RE = DEN*VEL*CHORD/VIS
      MACH = OMACH
   88 CAMB = CAMP
      CALL CLDVSZ( CAMB, TC, CLD, Z )
C     CRE = REYNOLDS NO. FUNCTION FOR OPTIMUM LIFT COEFFICIENT --
C     FROM FIG. 2-48, MCCORMICK
      CRE = -14.0*(ALOG10(RE)-6.0)+24.250
C     DTC = THICKNESS FUNCTION FOR OPTIMUM LIFT COEFFICIENT --
C     FROM FIG. 2-49, MCCORMICK
      DTC = -3.84375*TC+1
C     CLOPT FROM EQ. 2-44, MCCORMICK
      CLOPT = Z*CRE*DTC
      CALL MAXCL( Z, TC, CLMX )
      IF (ALPHA.EQ. 0.0) GO TO 40
      IF (TC .GE. .20) DCLDAL = .1321*(1-TC)/SQRT(1-TC**2)
      IF (TC .LT. .20) DCLDAL = .1216*(1-TC)/SQRT(1-TC**2)
      IF (TC .LT. .17) DCLDAL = .1175*(1-TC)/SQRT(1-TC**2)
      IF (TC .LT. .14) DCLDAL = .1134*(1-TC)/SQRT(1-TC**2)
      IF (TC .LT. .11) DCLDAL = .1043*(1-TC)/SQRT(1-TC**2)
      IF (TC .LT. .08) DCLDAL = .1039*(1-TC)/SQRT(1-TC**2)
      IF (TC .LT. .05) DCLDAL = .1021*(1-TC)/SQRT(1-TC**2)
      DCLDAL = DCLDAL/SQRT(1-MACH**2)
      DELCL = DCLDAL*ALPHA
      GO TO 50
   40 DELCL = 0.0
   50 CONTINUE
      CL = CLD+DELCL
C     X FROM EQ. 2-45, MCCORMICK    X = (CL - CLOPT)/(CLMX - CLOPT)
      X = (CL-CLOPT)/(CLMX-CLOPT)
      CALL CDL( X, Z, TC, DELCD, LFIXX8 )
      CALL CDMN( Z, TC, CDMN1 )
      CALL RECD ( RE, ERE )
C     CDMIN FROM EQ. 2-46, MCCORMICK
      CDMIN = CDMN1*ERE
      CD = CDMIN + DELCD
      RETURN
      END
C
C     SUBROUTINE ATMCON FINDS PARAMETERS AT GIVEN ALTITUDE
C     (the 4-digit listing's ATMCON, renamed: its arguments differ from
C     the 16-series one in atmcon.f; the arithmetic is the same)
      SUBROUTINE ATMCN4(ALT,DEN,VIS,WA)
      ALT = ALT*.3048
      SLOPE = -.0065
      TEMP = 288.16+SLOPE*ALT
      EXP = 2.718281828
      TSEA = 288.16
      PSEA = 101325.
      PRES1 = 22700.
      GRAV = 9.82
      R = 288.
      POWER = GRAV/(SLOPE*R)
      PRES = PSEA*(1/(TEMP/TSEA))**POWER
      IF(ALT .LE. 11000.) GO TO 4
      PRES = PRES1*EXP**(-GRAV/(R*216.66)*(ALT-11000.))
      TEMP = 216.66
    4 WA = SQRT(1.4*R*TEMP)/.3048
      TEMP = (TEMP-273.15)*9/5+491.67
      VIS = .35*(TEMP/492.)**1.5*(690/(TEMP+198.))*.000001
      PRES = PRES*2116.2/PSEA
      DEN = PRES/(1718.*TEMP)
      ALT = ALT/.3048
      RETURN
      END
