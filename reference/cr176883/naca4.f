      EQUIVALENCE(ZDATA(1,1), Z2 )
      EQUIVALENCE(ZDATA(1,2), Z4 )
      EQUIVALENCE(ZDATA(1,3), Z6 )
      EQUIVALENCE(ZDATA(1,4), Z8 )
